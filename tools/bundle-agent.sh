#!/bin/sh
# Builds plugins/tilori/vendor/tilori-agent.js, the tilori-agent CLI bundled
# into one JS file, from a tilori-agent release tag, and records where it came
# from in plugins/tilori/vendor/SOURCE.
#
#   sh tools/bundle-agent.sh v0.1.5   # update the bundle to a new tag
#   sh tools/bundle-agent.sh --verify # rebuild from the tag/commit in SOURCE
#                                     # and fail unless it matches byte for byte
#
# Reproducible: a fresh clone of the tag, `bun install --frozen-lockfile
# --ignore-scripts`, `bun build --target=bun`. Output depends only on the
# tagged tree and the Bun version, so SOURCE pins the Bun version and
# --verify refuses to compare with a different one. Needs gh (the repo is
# private), git and Bun. Writes nothing outside the repo except a temp dir.
set -eu
cd "$(dirname "$0")/.."
vendor=plugins/tilori/vendor
repo=universal-market/tilori-agent
BUN="${BUN:-$(command -v bun || echo "$HOME/.bun/bin/bun")}"
[ -x "$BUN" ] || { echo "bundle-agent: bun not found" >&2; exit 1; }
bun_version=$("$BUN" --version)

sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
field() { sed -n "s/^$1=//p" "$vendor/SOURCE"; }

verify=false
case "${1:-}" in
  --verify)
    verify=true
    tag=$(field tag); want_commit=$(field commit); want_bun=$(field bun); want_sha=$(field sha256)
    [ "$bun_version" = "$want_bun" ] || {
      echo "bundle-agent: SOURCE was built with Bun $want_bun, this is Bun $bun_version; set BUN to a Bun $want_bun binary to verify" >&2
      exit 1
    } ;;
  v[0-9]*) tag=$1; want_commit= ;;
  *) echo "usage: sh tools/bundle-agent.sh <tag> | --verify" >&2; exit 2 ;;
esac

t=$(mktemp -d); trap 'rm -rf "$t"' EXIT
gh repo clone "$repo" "$t/src" -- -q --depth 1 --branch "$tag" -c advice.detachedHead=false
commit=$(git -C "$t/src" rev-parse HEAD)
if [ -n "$want_commit" ] && [ "$commit" != "$want_commit" ]; then
  echo "bundle-agent: tag $tag now points at $commit, SOURCE pins $want_commit (tag moved?)" >&2
  exit 1
fi
(cd "$t/src" && "$BUN" install --frozen-lockfile --ignore-scripts >/dev/null \
  && "$BUN" build src/cli.ts --target=bun --outfile "$t/tilori-agent.js" >/dev/null)
sha=$(sha256 "$t/tilori-agent.js")

if $verify; then
  [ "$sha" = "$want_sha" ] || { echo "bundle-agent: rebuild of $tag is $sha, SOURCE says $want_sha" >&2; exit 1; }
  cmp -s "$t/tilori-agent.js" "$vendor/tilori-agent.js" \
    || { echo "bundle-agent: committed $vendor/tilori-agent.js differs from the rebuild of $tag" >&2; exit 1; }
  echo "bundle-agent: $vendor/tilori-agent.js matches a rebuild of $tag ($commit)"
  exit 0
fi

cp "$t/tilori-agent.js" "$vendor/tilori-agent.js"
chmod 644 "$vendor/tilori-agent.js"
cat > "$vendor/SOURCE" <<SRC
# Generated by tools/bundle-agent.sh; do not edit. Verify with --verify.
repo=$repo
tag=$tag
commit=$commit
bun=$bun_version
sha256=$sha
SRC
echo "bundle-agent: wrote $vendor/tilori-agent.js from $tag ($commit), sha256 $sha"
